#!/usr/bin/env node
/**
 * Generates the Markdown mirror of the site from its HTML pages, so a mirror
 * can't drift from the page it describes:
 *
 *   <page>/index.md            one per canonical page (the homepage is /index.md)
 *   /llms.txt, /sitemap.md     entry points listing every mirror
 *   /llm/topics/<topic>.md     one map per topic
 *   public/_headers            the block between the markdown-mirrors markers
 *
 * The page list comes from the sitemap (scripts/generate-sitemap.js), so a
 * disabled platform disappears from the mirrors as well. tests/markdown.test.js
 * fails if any generated file is out of date.
 *
 *   npm run generate:markdown          write the files
 *   npm run generate:markdown -- --check   exit 1 if anything is out of date
 *
 * No dependencies: the HTML is hand-written and regular, so a small parser is
 * enough. Only <main> is converted. A calculator page keeps its intro, its
 * "which query should I paste" help and the list of inputs; the interactive
 * result panel is replaced by a short "What you get" section.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASE_URL, sitemapPaths } from './generate-sitemap.js';
import { PLATFORM_CATEGORIES, PLATFORM_DEFINITIONS, SIZING_MODEL_GUIDE, getEnabledPlatforms } from '../public/js/platforms.js';
import { LINKS, reportBugUrl } from '../public/js/links.js';

export const PUBLIC_DIR = join(import.meta.dirname, '..', 'public');
export const HEADERS_START = '# markdown-mirrors:start (generated by scripts/generate-markdown.js; do not edit)';
export const HEADERS_END = '# markdown-mirrors:end';
const OWNER = 'MemoryLimit maintainers (github.com/torrentalle/memorylimit-dev)';
const MD_TYPE = 'text/markdown; charset=utf-8';

// --- A small HTML parser ------------------------------------------------

const VOID_TAGS = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);
const RAW_TEXT_TAGS = new Set(['script', 'style']);
const NAMED_ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', hellip: '…', ndash: '–', mdash: '—', rarr: '→', larr: '←' };

function decodeEntities(text) {
  return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, body) => {
    if (body[0] === '#') {
      const code = body[1].toLowerCase() === 'x' ? parseInt(body.slice(2), 16) : parseInt(body.slice(1), 10);
      return String.fromCodePoint(code);
    }
    return NAMED_ENTITIES[body.toLowerCase()] ?? match;
  });
}

function parseAttributes(source) {
  const attrs = {};
  for (const m of source.matchAll(/([^\s"'<>/=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+)))?/g)) {
    attrs[m[1].toLowerCase()] = decodeEntities(m[2] ?? m[3] ?? m[4] ?? '');
  }
  return attrs;
}

/** Parses well-formed, hand-written HTML into { tag, attrs, children } nodes; text nodes are { text }. */
export function parseHtml(html) {
  const root = { tag: '#root', attrs: {}, children: [] };
  const stack = [root];
  const token = /<!--[\s\S]*?-->|<!doctype[^>]*>|<(\/?)([a-zA-Z][a-zA-Z0-9-]*)((?:"[^"]*"|'[^']*'|[^'">])*?)(\/?)>|([^<]+|<)/gi;
  let match;
  while ((match = token.exec(html)) !== null) {
    const [whole, closing, rawTag, attrSource, selfClosing, text] = match;
    if (whole.startsWith('<!')) continue;
    if (text !== undefined) {
      stack.at(-1).children.push({ text: decodeEntities(text) });
      continue;
    }
    const tag = rawTag.toLowerCase();
    if (closing) {
      const at = stack.findLastIndex((node) => node.tag === tag);
      if (at > 0) stack.length = at;
      continue;
    }
    const node = { tag, attrs: parseAttributes(attrSource), children: [] };
    stack.at(-1).children.push(node);
    if (VOID_TAGS.has(tag) || selfClosing) continue;
    if (RAW_TEXT_TAGS.has(tag)) {
      const end = html.toLowerCase().indexOf(`</${tag}`, token.lastIndex);
      token.lastIndex = end === -1 ? html.length : html.indexOf('>', end) + 1;
      continue;
    }
    stack.push(node);
  }
  return root;
}

const isElement = (node) => node.tag !== undefined;
const classesOf = (node) => (node.attrs?.class ?? '').split(/\s+/).filter(Boolean);
const hasClass = (node, name) => classesOf(node).includes(name);
const elementChildren = (node) => node.children.filter(isElement);
const textOf = (node) => (node.text !== undefined ? node.text : node.children.map(textOf).join(''));

function find(node, predicate) {
  for (const child of node.children ?? []) {
    if (!isElement(child)) continue;
    if (predicate(child)) return child;
    const inner = find(child, predicate);
    if (inner) return inner;
  }
  return null;
}

// --- HTML → Markdown ----------------------------------------------------

const SKIP_TAGS = new Set(['script', 'style', 'button', 'textarea', 'input', 'svg', 'noscript', 'img', 'nav', 'header', 'footer', 'select']);

/** GitHub-style heading slug. */
export function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .trim()
    .replace(/\s/g, '-');
}

const ANCHOR_OPEN = '\u0000A:';
const ANCHOR_CLOSE = '\u0000';

function isSkipped(node) {
  return (
    SKIP_TAGS.has(node.tag) ||
    node.attrs['aria-hidden'] === 'true' ||
    hasClass(node, 'visually-hidden') ||
    hasClass(node, 'panel__index') ||
    hasClass(node, 'prom-feedback') ||
    (hasClass(node, 'is-hidden') && hasClass(node, 'field'))
  );
}

/**
 * Converts one page's <main> to Markdown. Links to other pages and to #ids are
 * returned as placeholders and resolved once every page has been converted
 * (resolveLinks), because an anchor can point at another page.
 */
function convertMain(main, { pagePath, isCalculator }) {
  const blocks = [];
  const anchors = {}; // element id -> slug of the heading it sits under
  const slugCounts = {};
  let currentSlug = '';
  let pendingIds = [];
  const outputs = [];

  const inline = (node) => {
    let out = '';
    for (const child of node.children) {
      if (!isElement(child)) {
        out += child.text.replace(/\s+/g, ' ');
        continue;
      }
      if (isSkipped(child)) continue;
      if (child.attrs.id) anchors[child.attrs.id] = currentSlug;
      switch (child.tag) {
        case 'code':
          out += '`' + textOf(child).replace(/`/g, '') + '`';
          break;
        case 'strong':
        case 'b':
          out += '**' + inline(child).trim() + '**';
          break;
        case 'em':
        case 'i':
          out += '*' + inline(child).trim() + '*';
          break;
        case 'br':
          out += '  \n';
          break;
        case 'a': {
          const label = inline(child).trim();
          if (!label || label === '↩') break;
          out += `[${label}](${linkTarget(child.attrs.href ?? '')})`;
          break;
        }
        default:
          out += inline(child);
      }
    }
    return out;
  };

  const linkTarget = (href) => {
    if (href.startsWith('#')) return `${ANCHOR_OPEN}${pagePath}#${href.slice(1)}${ANCHOR_CLOSE}`;
    let url;
    try {
      url = new URL(href, BASE_URL + pagePath);
    } catch {
      return href;
    }
    if (url.origin !== BASE_URL) return url.href;
    return `${ANCHOR_OPEN}${url.pathname}${url.hash}${ANCHOR_CLOSE}`;
  };

  const flushIds = () => {
    for (const id of pendingIds) anchors[id] = currentSlug;
    pendingIds = [];
  };
  const emit = (text) => {
    if (text && text.trim()) blocks.push(text.trimEnd());
    flushIds();
  };
  const emitHeading = (node) => {
    const text = inline(node).replace(/\s+/g, ' ').trim();
    if (!text) return;
    const base = slugify(text);
    const seen = slugCounts[base] ?? 0;
    slugCounts[base] = seen + 1;
    currentSlug = seen === 0 ? base : `${base}-${seen}`;
    if (node.attrs.id) anchors[node.attrs.id] = currentSlug;
    flushIds();
    blocks.push('#'.repeat(Number(node.tag[1])) + ' ' + text);
  };

  const list = (node, depth, ordered) => {
    const lines = [];
    let n = 0;
    for (const item of elementChildren(node).filter((c) => c.tag === 'li')) {
      n += 1;
      const own = { children: item.children.filter((c) => !(isElement(c) && (c.tag === 'ul' || c.tag === 'ol'))) };
      lines.push('  '.repeat(depth) + (ordered ? `${n}. ` : '- ') + inline(own).trim());
      for (const nested of item.children.filter((c) => isElement(c) && (c.tag === 'ul' || c.tag === 'ol'))) {
        lines.push(list(nested, depth + 1, nested.tag === 'ol'));
      }
    }
    return lines.join('\n');
  };

  const cell = (node) => inline(node).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  const table = (node) => {
    const rows = [];
    const collect = (parent) => {
      for (const child of elementChildren(parent)) {
        if (child.tag === 'tr') {
          if (child.attrs.id) anchors[child.attrs.id] = currentSlug;
          rows.push({ header: elementChildren(child).some((c) => c.tag === 'th'), cells: elementChildren(child).map(cell) });
        } else collect(child);
      }
    };
    collect(node);
    if (!rows.length) return '';
    const width = Math.max(...rows.map((r) => r.cells.length));
    const padded = rows.map((r) => ({ ...r, cells: [...r.cells, ...Array(width - r.cells.length).fill('')] }));
    const hasHeader = padded[0].header;
    const head = hasHeader ? padded[0].cells : Array(width).fill(' ');
    const body = hasHeader ? padded.slice(1) : padded;
    return [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...body.map((r) => `| ${r.cells.join(' | ')} |`)].join('\n');
  };

  const field = (node) => {
    const label = find(node, (c) => c.tag === 'label');
    if (!label) return false;
    const unit = find(label, (c) => hasClass(c, 'field-unit'));
    const unitText = unit ? textOf(unit).trim() : '';
    let name = inline(label).trim();
    if (unitText) name = name.replace(unitText, '').trim();
    let line = `- **${name}**`;
    if (unitText) line += ` (${unitText})`;
    const select = find(node, (c) => c.tag === 'select');
    if (select) {
      const options = [];
      (function walk(parent) {
        for (const c of elementChildren(parent)) {
          if (c.tag === 'option') options.push(textOf(c).replace(/\s+/g, ' ').trim());
          else walk(c);
        }
      })(select);
      line += `: ${options.join('; ')}`;
    }
    const hint = find(node, (c) => hasClass(c, 'field-hint') || hasClass(c, 'field-help'));
    if (hint) line += ` — ${inline(hint).trim()}`;
    return line;
  };

  const visit = (parent) => {
    const kids = elementChildren(parent);
    for (const node of kids) {
      if (isSkipped(node)) continue;
      if (isCalculator && (hasClass(node, 'results') || node.attrs.id === 'disabled-state')) {
        // The interactive result panel: keep only the names of its sections.
        for (const h of findAll(node, (c) => c.tag === 'h2')) {
          const title = inline(h).replace(/\s+/g, ' ').trim();
          if (title && !/gauge/i.test(title)) outputs.push(title);
        }
        continue;
      }
      if (node.attrs.id && !/^h[1-6]$/.test(node.tag)) pendingIds.push(node.attrs.id);
      const tag = node.tag;
      let fieldLine = '';
      if (/^h[1-6]$/.test(tag)) emitHeading(node);
      else if (tag === 'p') emit(inline(node).trim());
      else if (tag === 'ul' || tag === 'ol') emit(list(node, 0, tag === 'ol'));
      else if (tag === 'table') emit(table(node));
      else if (tag === 'pre') emit('```\n' + textOf(node).replace(/\n+$/, '') + '\n```');
      else if (tag === 'blockquote') emit(inline(node).trim().split('\n').map((l) => `> ${l}`).join('\n'));
      else if (tag === 'summary') continue;
      else if (tag === 'details') {
        const summary = elementChildren(node).find((c) => c.tag === 'summary');
        if (summary) emit(`**${inline(summary).replace(/\s+/g, ' ').trim()}**`);
        visit(node);
      } else if (tag === 'label' && kids.some((c) => c.tag === 'textarea')) emit(`Paste box: ${inline(node).trim()}.`);
      else if (hasClass(node, 'field') && (fieldLine = field(node))) {
        blocks.push(fieldLine);
        flushIds();
      } else if (!node.children.some(isElement)) emit(inline(node).trim());
      else visit(node);
    }
  };

  visit(main);

  const joined = blocks.filter((block, i) => block !== blocks[i - 1]).reduce((acc, block, i, all) => {
    if (i === 0) return block;
    return acc + (block.startsWith('- ') && all[i - 1].startsWith('- ') ? '\n' : '\n\n') + block;
  }, '');
  return { markdown: joined, anchors, outputs };
}

function findAll(node, predicate, found = []) {
  for (const child of elementChildren(node)) {
    if (predicate(child)) found.push(child);
    findAll(child, predicate, found);
  }
  return found;
}

// --- Pages and outputs --------------------------------------------------

function pageFile(path) {
  return join(PUBLIC_DIR, path === '/' ? '' : path, 'index.html');
}

/** Where a page's mirror lives, relative to public/. */
export const mirrorPath = (path) => (path === '/' ? 'index.md' : `${path.slice(1)}index.md`);
const mirrorUrl = (path) => `${BASE_URL}/${mirrorPath(path)}`;

function pageInfo(path) {
  const defs = getEnabledPlatforms();
  const calculator = defs.find((def) => def.path === path);
  const guideOf = defs.find((def) => def.guide === path);
  if (calculator) return { kind: 'calculator', topic: calculator.category, def: calculator };
  if (guideOf || path === SIZING_MODEL_GUIDE) return { kind: 'guide', topic: 'guides', def: guideOf ?? null };
  return { kind: path === '/' ? 'home' : 'site', topic: 'site', def: null };
}

function readPage(path) {
  const tree = parseHtml(readFileSync(pageFile(path), 'utf8'));
  const main = find(tree, (n) => n.tag === 'main');
  const h1 = find(main, (n) => n.tag === 'h1');
  const description = find(tree, (n) => n.tag === 'meta' && n.attrs.name === 'description');
  if (!main || !h1 || !description) throw new Error(`${path}: needs <main>, an <h1> and a meta description`);
  return { main, title: textOf(h1).replace(/\s+/g, ' ').trim(), description: description.attrs.content.trim(), url: `${BASE_URL}${path}` };
}

function siteSummary() {
  const labels = getEnabledPlatforms().map((def) => def.label);
  return `Memory sizing calculators and guides for ${labels.slice(0, -1).join(', ')} and ${labels.at(-1)}. Paste observed usage, get ready-to-use configuration; everything runs in the browser.`;
}

function homeBody(page, introMarkdown) {
  const parts = [introMarkdown];
  for (const category of PLATFORM_CATEGORIES) {
    const defs = getEnabledPlatforms().filter((def) => def.category === category.id);
    if (!defs.length) continue;
    parts.push(`## ${category.label}`, defs.map((def) => `- [${def.label}](${mirrorUrl(def.path)}): ${def.tagline}`).join('\n'));
  }
  parts.push('## How the numbers are calculated', `- [The shared sizing model](${mirrorUrl(SIZING_MODEL_GUIDE)}): the formula, margin tables and assumptions every calculator uses. Each calculator also has its own "how it works" guide.`);
  return parts.join('\n\n');
}

function resolveLinks(markdown, anchorMaps, knownPaths) {
  return markdown.replace(new RegExp(`${ANCHOR_OPEN}([^#\\u0000]*)(?:#([^\\u0000]*))?${ANCHOR_CLOSE}`, 'g'), (whole, path, hash) => {
    if (knownPaths.has(path)) {
      const slug = hash ? anchorMaps[path]?.[hash] : '';
      return mirrorUrl(path) + (slug ? `#${slug}` : '');
    }
    // Not one of the mirrored pages (a file such as /favicon.ico): keep the site URL.
    return `${BASE_URL}${path}${hash ? `#${hash}` : ''}`;
  });
}

/** Builds every generated file: { files: Map(relative path → text), headers: block for public/_headers }. */
export function buildMarkdownSite() {
  const paths = sitemapPaths();
  const known = new Set(paths);
  const pages = paths.map((path) => {
    const info = pageInfo(path);
    const page = readPage(path);
    const intro = info.kind === 'home' ? find(page.main, (n) => hasClass(n, 'intro-text')) : null;
    const converted =
      info.kind === 'home'
        ? { markdown: '', anchors: {}, outputs: [] }
        : convertMain(page.main, { pagePath: path, isCalculator: info.kind === 'calculator' });
    if (info.kind === 'home') {
      const introMd = convertMain({ children: [intro], tag: 'div', attrs: {} }, { pagePath: path, isCalculator: false });
      converted.markdown = introMd.markdown;
    }
    return { path, info, ...page, ...converted };
  });
  const anchorMaps = Object.fromEntries(pages.map((p) => [p.path, p.anchors]));

  const files = new Map();
  const origin = BASE_URL;
  for (const page of pages) {
    let body = page.markdown;
    // The H1 becomes the document title below.
    body = body.replace(/(^|\n)# [^\n]*\n*/, '$1');
    if (page.info.kind === 'home') body = homeBody(page, body);
    if (page.info.kind === 'calculator') {
      const label = page.info.def.label;
      body +=
        '\n\n## What you get\n\n' +
        (page.outputs.length ? page.outputs.map((o) => `- ${o}`).join('\n') + '\n\n' : '') +
        'The calculator shows the result and a step-by-step derivation after you enter usage data. ' +
        'Everything is calculated in your browser; nothing you enter is sent anywhere.\n\n' +
        `How every number is calculated, with sources and assumptions: [guide](${mirrorUrl(page.info.def.guide ?? SIZING_MODEL_GUIDE)}). ` +
        `Wrong result? [Report it](${reportBugUrl(label)}).`;
    }
    const header =
      `# ${page.title}\n\nCanonical: [${page.title}](${page.url})\n\nLocale: en\n\nPurpose: ${page.description}\n\n` +
      `Maintenance owner: ${OWNER}\n\n[Topic map](${origin}/llm/topics/${page.info.topic}.md) · [Complete scoped map](${origin}/sitemap.md)\n\n`;
    files.set(mirrorPath(page.path), resolveLinks(header + body, anchorMaps, known).trim() + '\n');
  }

  const topics = [...new Set(pages.map((p) => p.info.topic))].sort();
  const row = (p) => `- [${p.title}](${mirrorUrl(p.path)}): ${p.description} (en); [canonical page](${p.url}).`;
  const topicLinks = topics.map((t) => `- [${t}](${origin}/llm/topics/${t}.md): All public ${t} documents in this inventory.`).join('\n');
  const summary = siteSummary();
  files.set(
    'sitemap.md',
    `# MemoryLimit content map\n\nInventory scope: complete. Public documents: ${pages.length}.\n\n${summary}\n\n## Topics\n\n${topicLinks}\n\n## All public documents\n\n${pages.map(row).join('\n')}\n`
  );
  for (const topic of topics) {
    files.set(`llm/topics/${topic}.md`, `# ${topic}\n\n[Site content map](${origin}/sitemap.md)\n\n${pages.filter((p) => p.info.topic === topic).map(row).join('\n')}\n`);
  }
  files.set(
    'llms.txt',
    `# MemoryLimit\n\n> ${summary}\n\nInventory scope: complete. Content is maintained by ${OWNER}.\n\n` +
      `If you are an LLM looking for site information, use the [content map](${origin}/sitemap.md) to locate the relevant topic and its linked Markdown answer.\n` +
      "Use that document's cited sources and canonical page; if the requested information is absent, report that gap.\n\n" +
      `## Content map\n\n- [Site content map](${origin}/sitemap.md): All public document destinations within the declared inventory.\n\n## Topics\n\n${topicLinks}\n`
  );

  const headerRules = [
    HEADERS_START,
    '# Each mirror names its canonical HTML page; index policy: canonical-to-html (no noindex).',
    '/llms.txt',
    '  Content-Type: text/plain; charset=utf-8',
    '/sitemap.md',
    `  Content-Type: ${MD_TYPE}`,
    '/llm/topics/*',
    `  Content-Type: ${MD_TYPE}`,
    ...pages.flatMap((p) => [`/${mirrorPath(p.path)}`, `  Content-Type: ${MD_TYPE}`, `  Link: <${p.url}>; rel="canonical"`]),
    HEADERS_END
  ].join('\n');
  return { files, headers: headerRules };
}

/** public/_headers with its generated block replaced (or appended when the markers are absent). */
export function withHeadersBlock(current, block) {
  const start = current.indexOf(HEADERS_START);
  const end = current.indexOf(HEADERS_END);
  if (start === -1 || end === -1) return `${current.replace(/\n*$/, '\n')}\n${block}\n`;
  return current.slice(0, start) + block + current.slice(end + HEADERS_END.length);
}

/** Paths (relative to public/) of mirror files on disk that the generator would not produce. */
export function staleFiles(files) {
  const found = [];
  const walk = (dir, rel) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const relPath = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        if (entry.name !== 'js' && entry.name !== 'css' && entry.name !== 'fonts' && entry.name !== 'brand') walk(join(dir, entry.name), relPath);
      } else if (entry.name === 'index.md' || relPath.startsWith('llm/')) found.push(relPath);
    }
  };
  walk(PUBLIC_DIR, '');
  return found.filter((p) => !files.has(p));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { files, headers } = buildMarkdownSite();
  const headersPath = join(PUBLIC_DIR, '_headers');
  const nextHeaders = withHeadersBlock(readFileSync(headersPath, 'utf8'), headers);
  const problems = [];
  for (const [rel, text] of files) {
    const target = join(PUBLIC_DIR, rel);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== text) problems.push(rel);
    if (!check) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
  }
  const stale = staleFiles(files);
  if (readFileSync(headersPath, 'utf8') !== nextHeaders) problems.push('_headers');
  if (check) {
    for (const rel of stale) problems.push(`${rel} (no longer generated)`);
    if (problems.length) {
      console.error(`Out of date — run npm run generate:markdown:\n${problems.map((p) => `  ${p}`).join('\n')}`);
      process.exit(1);
    }
    console.log(`Markdown mirrors are up to date (${files.size} files).`);
  } else {
    for (const rel of stale) rmSync(join(PUBLIC_DIR, rel));
    writeFileSync(headersPath, nextHeaders);
    console.log(`Wrote ${files.size} Markdown files and the _headers block${stale.length ? `; removed ${stale.length} stale file(s)` : ''}.`);
  }
}
